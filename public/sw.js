const CACHE_NAME = "zynth-static-v2";
const PRECACHE = [
  "/manifest.webmanifest",
  "/icons/zynth-icon.svg",
  "/icons/zynth-apple-touch-icon.png"
];

self.addEventListener("install", event => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then(cache => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(
        keys.filter(key => key !== CACHE_NAME).map(key => caches.delete(key))
      ))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("message", event => {
  if (event.data?.type === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("fetch", event => {
  if (event.request.method !== "GET") return;
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin) return;

  // Never cache HTML/documents: ZYNTH pages are authenticated and must stay network-fresh.
  if (event.request.mode === "navigate" || event.request.destination === "document") return;

  // Cache static assets after the first successful network response.
  const cacheable = ["script", "style", "image", "font", "manifest"];
  if (!cacheable.includes(event.request.destination)) return;

  event.respondWith(
    fetch(event.request)
      .then(response => {
        if (response.ok) {
          const copy = response.clone();
          caches.open(CACHE_NAME).then(cache => cache.put(event.request, copy));
        }
        return response;
      })
      .catch(() => caches.match(event.request))
  );
});